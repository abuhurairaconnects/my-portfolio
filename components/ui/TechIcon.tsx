export function TechIcon({
  icon,
  name,
  className = "w-5 h-5",
}: TechIconProps): React.ReactElement {
  const normalizedKey = icon.toLowerCase().replace(/[^a-z0-9]/g, "");

  if (SVG_ICONS[normalizedKey]) {
    return <div className={`inline-block shrink-0 ${className}`}>{SVG_ICONS[normalizedKey]}</div>;
  }

  // Semantic fallback Lucide icons based on keyword
  let Fallback = Code2;
  if (normalizedKey.includes("sql") || normalizedKey.includes("db") || normalizedKey.includes("house") || normalizedKey.includes("prisma")) {
    Fallback = Database;
  } else if (normalizedKey.includes("node") || normalizedKey.includes("go") || normalizedKey.includes("server")) {
    Fallback = Server;
  } else if (normalizedKey.includes("kube") || normalizedKey.includes("docker") || normalizedKey.includes("form")) {
    Fallback = Box;
  } else if (normalizedKey.includes("cloud")) {
    Fallback = Cloud;
  }

  return <Fallback className={className} aria-label={name} />;
}
